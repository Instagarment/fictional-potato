// Builds shopify.app.toml: the app's name, web address, permissions and
// webhooks, which Shopify reads when you run `shopify app deploy`.
export function buildShopifyToml({ clientId, appUrl, appName, apiVersion = '2026-10' }) {
  const q = JSON.stringify;
  return `# Generated by Instagarment Print on Demand. Upload with: npx @shopify/cli@latest app deploy
name = ${q(appName)}
client_id = ${q(clientId)}
application_url = ${q(`${appUrl}/app`)}
embedded = true

[access_scopes]
# read_orders + write_orders: read new orders and tag them "to print" / "printed"
# write_products: tag the products the store owner chooses for Instagarment to print
scopes = "read_orders,write_orders,write_products"

[auth]
redirect_urls = [ ${q(`${appUrl}/app`)} ]

[webhooks]
api_version = ${q(apiVersion)}

  [[webhooks.subscriptions]]
  topics = [ "orders/create", "app/uninstalled" ]
  uri = ${q(`${appUrl}/webhooks`)}

  [[webhooks.subscriptions]]
  compliance_topics = [ "customers/data_request", "customers/redact", "shop/redact" ]
  uri = ${q(`${appUrl}/webhooks`)}

[pos]
embedded = false
`;
}
